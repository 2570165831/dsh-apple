#!/bin/bash
# Build the three iSH static libraries for the iOS simulator (arm64).
#
#   libish.a      kernel, processes, syscalls, sockets, PTY, mounts
#   libish_emu.a  the ARM64 interpreter plus the guest ARM64 VDSO
#   libfakefs.a   the SQLite-backed filesystem metadata store
#
# Output: build/ish/<platform>/<configuration>/{libish,libish_emu,libfakefs}.a
#         build/ish/<platform>/<configuration>/libvdso.so.elf
#
# Usage:
#   ish/scripts/build-ish.sh [-c Debug|Release] [-p iphonesimulator|iphoneos] [-C]
#     -C   build from a clean directory (deletes the build dir first)
#
# The script refuses to build a source tree that does not match
# ish/UPSTREAM.lock.json, so the libraries always correspond to a stated commit
# plus the patch series in ish/patches/.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ISH_DIR="$(cd "$HERE/.." && pwd)"
ROOT="$(cd "$ISH_DIR/.." && pwd)"
SRC="$ISH_DIR/src/ish-arm64"

CONFIGURATION="Release"
PLATFORM="iphonesimulator"
CLEAN=0
while getopts ":c:p:Ch" opt; do
    case "$opt" in
        c) CONFIGURATION="$OPTARG" ;;
        p) PLATFORM="$OPTARG" ;;
        C) CLEAN=1 ;;
        h) sed -n '2,22p' "$0"; exit 0 ;;
        *) echo "unknown option: -$OPTARG" >&2; exit 2 ;;
    esac
done

case "$PLATFORM" in
    iphonesimulator|iphoneos) ;;
    *) echo "unsupported platform: $PLATFORM" >&2; exit 2 ;;
esac

log() { printf '\033[1;34m==> %s\033[0m\n' "$*"; }
die() { printf '\033[1;31merror: %s\033[0m\n' "$*" >&2; exit 1; }

# shellcheck source=../../scripts/toolchain.sh
. "$ROOT/scripts/toolchain.sh"

if [ "$PLATFORM" = "iphonesimulator" ]; then
    SDK="$SDKROOT_SIM"
    TARGET_TRIPLE="arm64-apple-ios17.0-simulator"
else
    SDK="$(xcrun --sdk iphoneos --show-sdk-path)"
    TARGET_TRIPLE="arm64-apple-ios17.0"
fi

BUILD_ROOT="$ROOT/build/ish/$PLATFORM/$CONFIGURATION"
[ "$CLEAN" = 1 ] && rm -rf "$BUILD_ROOT"
mkdir -p "$BUILD_ROOT"
BUILD_DIR="$BUILD_ROOT/ninja"

log "source state"
"$ISH_DIR/scripts/fetch-sources.sh" --check

# Pin the string the guest reports in `uname -v`. Upstream interpolates
# __DATE__/__TIME__ there, which makes one object (kernel_uname.c.o) differ on
# every build and takes every library containing it with it. ish/patches/0001
# replaces those macros with ISH_BUILD_VERSION; the value is the source revision
# this build came from, so the string is both deterministic and informative.
#
# It goes in the cross file's c_args, not a separate meson option, because iSH's
# tools/staticdefine.sh rebuilds the compile command from compile_commands.json:
# a flag meson records there is a flag that script sees too.
SOURCE_COMMIT="$(head -1 "$ISH_DIR/.source-state" | cut -d' ' -f2)"
[ -n "$SOURCE_COMMIT" ] || die "could not read the source commit from ish/.source-state"

# NOTE: `c` is the bare word `clang`, not an absolute path, and every flag lives
# in c_args. Reason: iSH's tools/staticdefine.sh reads compile_commands.json,
# splits the recorded command on whitespace, and re-executes the pieces through
# the shell. Meson quotes any compiler path containing a character it considers
# special, so an absolute path there comes back as `'/Volumes/.../clang'` with
# the quote characters intact and the command never runs. That failure is
# silent: cpu-offsets.h is left empty and every gadget assembly line then fails
# with "expected compatible register, symbol or integer in range [0, 4095]".
# Keep this a bare binary name; scripts/toolchain.sh puts its directory first on
# PATH.
cat > "$BUILD_ROOT/cross.ini" <<EOF
# Generated by ish/scripts/build-ish.sh. Not hand-edited: the SDK path and the
# compiler differ per machine and per Xcode version.
[binaries]
c = 'clang'
ar = 'ar'
strip = 'strip'
pkg-config = 'false'

[host_machine]
system = 'darwin'
cpu_family = 'aarch64'
cpu = 'aarch64'
endian = 'little'

[built-in options]
c_args = ['-arch', 'arm64', '-target', '$TARGET_TRIPLE', '-isysroot', '$SDK', '-mios-simulator-version-min=17.0', '-DISH_BUILD_VERSION=ish-${SOURCE_COMMIT:0:8}']
c_link_args = ['-arch', 'arm64', '-target', '$TARGET_TRIPLE', '-isysroot', '$SDK', '-L$SDK/usr/lib']

[properties]
needs_exe_wrapper = true
sys_root = '$SDK'
library_dirs = ['$SDK/usr/lib']
EOF
if [ "$PLATFORM" = "iphoneos" ]; then
    sed -i '' -e 's/-mios-simulator-version-min=17.0/-miphoneos-version-min=17.0/' \
              -e "s/-simulator//" "$BUILD_ROOT/cross.ini"
fi

BUILDTYPE=release
[ "$CONFIGURATION" = "Debug" ] && BUILDTYPE=debug

# Meson reads a cross file's compiler and linker arguments at the first `setup`
# only; `--reconfigure` and ninja's own regeneration keep the old ones. So an
# Xcode update that renames the SDK (iPhoneSimulator27.1.sdk -> 27.2.sdk) leaves
# a build directory that links against a path that no longer exists, and the
# next regeneration fails with "library 'sqlite3' not found". A changed cross
# file therefore gets a fresh build directory; the old one is set aside, not
# deleted.
if [ -f "$BUILD_DIR/build.ninja" ] && ! cmp -s "$BUILD_ROOT/cross.ini" "$BUILD_DIR/.cross.ini.used"; then
    STALE="$BUILD_DIR.stale-$(date +%Y%m%d-%H%M%S)"
    log "cross file changed since this build directory was configured; moving it to $STALE"
    mv "$BUILD_DIR" "$STALE"
fi

if [ ! -f "$BUILD_DIR/build.ninja" ]; then
    log "configuring meson ($BUILDTYPE, $PLATFORM arm64)"
    "$MESON" setup "$BUILD_DIR" "$SRC" \
        --cross-file "$BUILD_ROOT/cross.ini" \
        --buildtype "$BUILDTYPE" \
        -Db_ndebug=true \
        -Dlog= \
        -Dlog_handler=nslog \
        -Dkernel=ish \
        -Dengine=asbestos \
        -Dguest_arch=arm64
    cp "$BUILD_ROOT/cross.ini" "$BUILD_DIR/.cross.ini.used"
fi

log "building"
"$NINJA" -C "$BUILD_DIR" libish.a libish_emu.a libfakefs.a vdso/arm64/libvdso.so.elf

for lib in libish.a libish_emu.a libfakefs.a; do
    [ -s "$BUILD_DIR/$lib" ] || die "$lib is missing or empty"
done

# The VDSO is the single most silent failure mode in this build: if lld is
# missing, meson writes an empty file, the libraries still link, and every guest
# process dies at its first syscall. So check that it is a real aarch64 ELF.
# Normalise the archive headers (mtime/uid/gid/mode). Without this the archives
# differ on every build even though every member object is identical: Darwin's
# ar has no deterministic mode and writes the wall-clock mtime into each header.
for lib in libish.a libish_emu.a libfakefs.a; do
    python3 "$ISH_DIR/scripts/normalize-archive.py" "$BUILD_DIR/$lib"
done

VDSO="$BUILD_DIR/vdso/arm64/libvdso.so.elf"
[ -s "$VDSO" ] || die "the guest VDSO is empty — ld.lld did not produce it, nothing would run"
if ! file "$VDSO" | grep -q 'ELF 64-bit LSB.*ARM aarch64'; then
    die "the guest VDSO is not an aarch64 ELF: $(file "$VDSO")"
fi

log "products"
for lib in libish.a libish_emu.a libfakefs.a; do
    printf '  %-16s %8s bytes  %s\n' "$lib" "$(stat -f%z "$BUILD_DIR/$lib")" \
        "$(shasum -a 256 "$BUILD_DIR/$lib" | awk '{print $1}')"
done
printf '  %-16s %8s bytes\n' "libvdso.so.elf" "$(stat -f%z "$VDSO")"

# Record the digest so build-artifact checks can tell two builds apart without
# hashing everything again.
{
    echo "platform $PLATFORM"
    echo "configuration $CONFIGURATION"
    echo "source $(cat "$ISH_DIR/.source-state" | head -1)"
    for lib in libish.a libish_emu.a libfakefs.a vdso/arm64/libvdso.so.elf; do
        echo "artifact $lib $(stat -f%z "$BUILD_DIR/$lib") $(shasum -a 256 "$BUILD_DIR/$lib" | awk '{print $1}')"
    done
} > "$BUILD_ROOT/ARTIFACTS.lock"
log "wrote $BUILD_ROOT/ARTIFACTS.lock"
