#!/usr/bin/env python3
"""Render and check notices from the installed database captured by build-rootfs.sh."""

import re
import sys
from pathlib import Path

BEGIN = "ROOTFS-INSTALLED-BEGIN"
END = "ROOTFS-INSTALLED-END"
COMPONENT = re.compile(r"[A-Za-z0-9][A-Za-z0-9._+-]*")


def license_ids(expression):
    if re.search(r"\bcustom:", expression, re.I):
        raise ValueError(f"custom Alpine license needs an explicit reviewed mapping: {expression}")
    tokens = re.findall(r"\(|\)|[A-Za-z0-9][A-Za-z0-9.+-]*", expression)
    if "".join(tokens) != re.sub(r"\s+", "", expression):
        raise ValueError(f"unsupported license expression: {expression}")
    identifiers = {
        token for token in tokens
        if token not in ("(", ")") and token.upper() not in ("AND", "OR", "WITH")
    }
    if not identifiers:
        raise ValueError("empty license expression")
    # Require both alternatives and every exception text; do not choose a license.
    return identifiers


def packages(text):
    lines = text.splitlines()
    if lines.count(BEGIN) != 1 or lines.count(END) != 1:
        raise ValueError("incomplete installed database capture")
    start, end = lines.index(BEGIN), lines.index(END)
    if start >= end:
        raise ValueError("invalid installed database capture")
    result, record = [], {}
    for line in lines[start + 1:end] + [""]:
        if not line.strip():
            if record:
                if not all(record.get(key) for key in ("P", "V", "L", "o")):
                    raise ValueError(f"incomplete package metadata: {record.get('P', '?')}")
                for key in ("P", "V", "o"):
                    if not COMPONENT.fullmatch(record[key]):
                        raise ValueError(f"invalid package metadata: {record[key]}")
                result.append(record)
                record = {}
            continue
        key, separator, value = line.partition(":")
        if separator and key in ("P", "V", "L", "o"):
            if key in record:
                raise ValueError(f"duplicate installed field: {key}")
            record[key] = value.strip()
    if not result or len({p["P"] for p in result}) != len(result):
        raise ValueError("empty or duplicate installed package inventory")
    return sorted(result, key=lambda package: package["P"])


def check(inventory, directory):
    required, problems = set(), []
    for package in inventory:
        try:
            for identifier in license_ids(package["L"]):
                required.add(directory / "texts" / f"{identifier}.txt")
        except ValueError as error:
            problems.append(f'{package["P"]}: {error}')
        required.add(directory / "packages" / f'{package["o"]}@{package["V"]}.txt')
    problems.extend(
        f"missing or empty: {path}" for path in sorted(required)
        if not path.is_file() or not path.read_text(encoding="utf-8").strip()
    )
    if problems:
        raise ValueError("incomplete rootfs notices:\n" + "\n".join(problems))


def render(inventory):
    lines = [
        "# Packages in build/rootfs/ish-rootfs.tar.gz",
        "",
        "Generated by ish/scripts/build-rootfs.sh from /lib/apk/db/installed",
        "after apk-tools is removed. License expressions and source package names",
        "are Alpine metadata, not license texts or a corresponding-source archive.",
        "",
        "| Package | Version | License (Alpine metadata) | Source package |",
        "|---|---|---|---|",
    ]
    for package in inventory:
        lines.append("| " + " | ".join(f'`{package[key]}`' for key in ("P", "V", "L", "o")) + " |")
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 3:
        print("usage: rootfs-notices.py <ROOTFS-INSTALLED.txt> <LICENSES/rootfs>",
              file=sys.stderr)
        return 2
    try:
        inventory = packages(Path(argv[1]).read_text(encoding="utf-8"))
        # Keep the draft inventory available even when notices need more work.
        print(render(inventory), end="")
        check(inventory, Path(argv[2]))
    except (OSError, ValueError) as error:
        print(f"rootfs notices: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
